"""Regression tests: reproduce and verify the HTTP 500 on POST /api/v1/agent/events.

These tests send the exact event shape generated by agent v3.0.0 to verify the
backend accepts it successfully.
"""

import json
import pytest
from datetime import datetime, timezone, timedelta
from httpx import AsyncClient

from tests.integration.helpers import enroll_test_host


def _agent_v3_event(
    event_type: str,
    severity: str = "medium",
    description: str | None = None,
    source: str = "auth.log",
    raw_log: str | None = None,
    offset_seconds: int = 0,
) -> dict:
    """Build an event dict matching the exact shape agent v3.0.0 sends.

    Agent sends timestamps as: datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    Agent sends individual event dicts (not wrapped in metadata).
    Agent uses 'default=str' in json.dumps, so datetime objects become strings.
    """
    ts = datetime.now(timezone.utc) + timedelta(seconds=offset_seconds, microseconds=abs(offset_seconds))
    return {
        "event_type": event_type,
        "severity": severity,
        "description": description or f"Agent v3.0.0 test: {event_type}",
        "source": source,
        "raw_log": raw_log or f"agent-v3-test {event_type} from {source}",
        "timestamp": ts.strftime("%Y-%m-%dT%H:%M:%SZ"),
    }


def _agent_v3_batch(events: list[dict]) -> bytes:
    """Serialize like the agent does: json.dumps(data, separators=(',',':'), default=str)"""
    return json.dumps({"events": events}, separators=(",", ":"), default=str).encode()


@pytest.mark.asyncio
async def test_single_v3_event_accepted(client: AsyncClient, admin_client: AsyncClient):
    """Single event in v3.0.0 format is accepted."""
    host_id, api_key = await enroll_test_host(admin_client, "v3-single-host")

    payload = [_agent_v3_event("ssh_login_failure")]
    res = await client.post(
        "/api/v1/agent/events",
        headers={"X-API-Key": api_key},
        json={"events": payload},
    )
    assert res.status_code == 200, f"Expected 200, got {res.status_code}: {res.text}"
    body = res.json()
    assert body["ingested"] == 1
    assert body["errors"] == []


