@pytest.mark.asyncio
async def test_v3_full_flush_cycle(client: AsyncClient, admin_client: AsyncClient):
    """Simulate the exact flush cycle: 43 events, then verify they appear in the DB."""
    host_id, api_key = await enroll_test_host(admin_client, "v3-flush-host")

    events = [_agent_v3_event("ssh_login_failure", offset_seconds=-i) for i in range(43)]
    res = await client.post(
        "/api/v1/agent/events",
        headers={"X-API-Key": api_key},
        json={"events": events},
    )
    assert res.status_code == 200, f"Expected 200, got {res.status_code}: {res.text}"

    # Verify events appear in the events listing
    events_res = await admin_client.get(
        "/api/v1/events",
        params={"host_id": host_id, "page_size": 50},
    )
    assert events_res.status_code == 200, events_res.text
    items = events_res.json()["items"]
    assert len(items) >= 1, f"Expected at least 1 event in DB, got {len(items)}"
    assert any(e["event_type"] == "ssh_login_failure" for e in items)


@pytest.mark.asyncio
async def test_v3_500_regression_with_sequential_requests(client: AsyncClient, admin_client: AsyncClient):
    """Reproduce the exact failure: multiple sequential POST /api/v1/agent/events.

    The agent sends heartbeat, then events, then metrics in sequence.
    This test sends events repeatedly to catch intermittent 500s.
    """
    host_id, api_key = await enroll_test_host(admin_client, "v3-seq-host")

    # Send heartbeat first (like the real agent does)
    hb_res = await client.post(
        "/api/v1/agent/heartbeat",
        headers={"X-API-Key": api_key},
        json={"agent_version": "3.0.0", "agent_hash": "test-hash"},
    )
    assert hb_res.status_code == 200, hb_res.text

    # Send 5 batches of 10 events (simulating the agent's 10-second log collection cycle)
    for batch_idx in range(5):
        events = [
            _agent_v3_event("ssh_login_failure", offset_seconds=-(batch_idx * 10 + i))
            for i in range(10)
        ]
        res = await client.post(
            "/api/v1/agent/events",
            headers={"X-API-Key": api_key},
            json={"events": events},
        )
        assert res.status_code == 200, (
            f"Batch {batch_idx}: Expected 200, got {res.status_code}: {res.text}"
        )


@pytest.mark.asyncio
async def test_mixed_metric_in_events_batch_does_not_500(client: AsyncClient, admin_client: AsyncClient):
    """Regression: metrics accidentally buffered as events used to 500 the whole batch."""
    host_id, api_key = await enroll_test_host(admin_client, "v3-mixed-metric-host")
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    payload = {
        "events": [
            _agent_v3_event("ssh_login_failure"),
            {
                "cpu_percent": 11.0,
                "memory_percent": 22.0,
                "disk_percent": 33.0,
                "recorded_at": ts,
            },
        ]
    }
    res = await client.post(
        "/api/v1/agent/events",
        headers={"X-API-Key": api_key},
        json=payload,
    )
    assert res.status_code == 200, res.text
    body = res.json()
    assert body["ingested"] == 1
    assert any("metric payload" in err for err in body["errors"])


